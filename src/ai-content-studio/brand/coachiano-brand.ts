export function buildImagePromptFromPost(topic: string, content: string, extra?: string) {
  const hook =
    String(content || '')
      .split('\n')
      .find((l) => /س\s*:/.test(l))
      ?.replace(/^.*س\s*:\s*/i, '')
      .replace(/["“”]/g, '')
      .trim()
      .slice(0, 90) || String(topic || '').slice(0, 90);
  const scene = String(content || topic || '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 700);
  const extraLine = String(extra || '').trim();
  return `Create a cinematic photorealistic Facebook/Instagram square photograph for the Arabic Egyptian parenting brand So7baFit / Coachiano.

Selected topic:
${topic}

One concrete moment to visualize:
${scene}

Arabic wall calligraphy (3–7 words, dark brown or gold, elegant):
${hook}

${COACHIANO_VISUAL_STYLE}
${extraLine ? `\nAdditional creative direction from editor:\n${extraLine}` : ''}`.trim();
}

